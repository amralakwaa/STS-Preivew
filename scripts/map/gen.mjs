import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';

// Run from a folder with world-atlas, d3-geo and topojson-client installed:
//   npm i world-atlas@2 d3-geo@3 topojson-client@3 && node scripts/map/gen.mjs
const topo = JSON.parse(readFileSync(new URL('../../node_modules/world-atlas/countries-50m.json', import.meta.url), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;
const ksa = countries.find((f) => f.properties.name === 'Saudi Arabia');
const W = 1000, H = 820;
const proj = geoMercator().fitExtent([[40, 40], [W - 40, H - 40]], ksa);
const path = geoPath(proj).digits(1);
// neighbours: clipped to the frame and rounded, they are only faint context
const clipped = geoMercator().scale(proj.scale()).translate(proj.translate()).clipExtent([[0, 0], [W, H]]);
const npath = geoPath(clipped).digits(0);

// neighbours, only those that touch the frame, drawn faintly for context
const near = ['Jordan', 'Iraq', 'Kuwait', 'Qatar', 'United Arab Emirates', 'Oman', 'Yemen', 'Bahrain', 'Egypt', 'Sudan', 'Eritrea', 'Israel', 'Palestine', 'Syria', 'Iran', 'Djibouti', 'Ethiopia'];
const neighbours = countries.filter((f) => near.includes(f.properties.name)).map((f) => npath(f)).filter(Boolean);

const pt = (lon, lat) => proj([lon, lat]).map((v) => Math.round(v * 10) / 10);
const cities = {
  riyadh: pt(46.6753, 24.7136),
  hq: pt(46.64, 24.82),
  jeddah: pt(39.1925, 21.4858),
  makkah: pt(39.8579, 21.3891),
  dammam: pt(50.0888, 26.4207),
  khobar: pt(50.1971, 26.2172),
};
const out = `// Generated by scripts/map (world-atlas 50m, Mercator fitted to the Kingdom). Do not edit by hand.
export const MAP = { w: ${W}, h: ${H} } as const;
export const KSA = ${JSON.stringify(path(ksa))};
export const NEIGHBOURS: string[] = ${JSON.stringify(neighbours)};
export const CITY_XY: Record<string, [number, number]> = ${JSON.stringify(cities)};
`;
writeFileSync(new URL('../../lib/map.ts', import.meta.url), out);
console.log('ksa path chars', path(ksa).length, 'neighbours', neighbours.length, cities);
